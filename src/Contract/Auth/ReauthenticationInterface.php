<?php
declare(strict_types=1);

namespace Mublo\Contract\Auth;

/**
 * 민감한 작업 직전의 본인 재확인
 *
 * 로그인된 세션만으로는 계정을 영구히 바꾸는 작업(비밀번호 설정·탈퇴 등)을 허용하지
 * 않는다. 자리를 비운 단말이나 탈취된 세션으로 계정을 장악하는 것을 막기 위해서다.
 *
 * 종전에는 "현재 비밀번호 입력"이 그 역할을 혼자 맡았다. 그러나 비밀번호가 확인 수단의
 * 전부는 아니다. SNS 로만 가입해 자기 비밀번호를 모르는 회원은 비밀번호를 댈 수 없고,
 * 그래서 비밀번호 설정도 탈퇴도 할 수 없는 막다른 길에 갇혔다.
 *
 * 그래서 확인 방법과 확인 사실을 분리한다. 코어는 "방금 본인 확인이 끝났다"는 사실만
 * 보고, 무엇으로 확인했는지는 묻지 않는다. 현재 비밀번호 확인은 그 사실을 만드는 여러
 * 방법 중 하나가 된다. 확장은 자기 방식(제공자 재로그인 등)으로 확인한 뒤 confirm()
 * 으로 같은 사실을 남긴다.
 *
 * 확인 사실은 짧게 만료된다. 한 번 확인하면 그 창 안에서는 다시 묻지 않는다.
 */
interface ReauthenticationInterface
{
    /**
     * 본인 확인이 방금 끝났음을 기록한다.
     *
     * 호출자가 확인 자체를 책임진다 — 이 메서드는 검증하지 않고 사실만 남긴다.
     * 확인되지 않은 회원에게 호출하면 그 회원의 계정을 넘기는 것과 같다.
     */
    public function confirm(int $memberId): void;

    /**
     * 이 회원의 본인 확인이 아직 유효한지.
     *
     * 다른 회원 앞으로 남은 확인은 통과시키지 않는다.
     */
    public function isConfirmed(int $memberId): bool;
}
